/**
 * `shipguard ignore`: a reason is required, critical only from a terminal, entries live in the
 * policy file (no inline markers), and the scanner honours them. (spec 03, 04; plan W3)
 */
import { execFileSync, spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, utimesSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import YAML from 'yaml'
import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest'
import { runIgnore, type IgnoreDeps } from '../../src/commands/ignore.js'
import { buildIgnoreRules, classifyIgnored, readIgnoreEntries } from '../../src/core/ignore.js'
import { applyPolicyIgnores } from '../../src/core/suppression.js'
import { writeGateRecord } from '../../src/core/gate-state.js'
import type { Finding, Policy } from '@agenticcli/shared'

vi.setConfig({ testTimeout: 60_000 })

const roots: string[] = []
afterAll(() => roots.forEach((d) => rmSync(d, { recursive: true, force: true })))

function project(files: Record<string, string> = {}): string {
  const dir = mkdtempSync(join(tmpdir(), 'sg-ignore-'))
  roots.push(dir)
  writeFileSync(join(dir, 'package.json'), '{}')
  for (const [name, body] of Object.entries(files)) {
    mkdirSync(join(dir, name, '..'), { recursive: true })
    writeFileSync(join(dir, name), body)
  }
  return dir
}

function deps(cwd: string, over: Partial<IgnoreDeps> = {}): IgnoreDeps & { lines: string[] } {
  const lines: string[] = []
  return { cwd, isTerminal: () => false, confirm: async () => true, now: () => new Date('2026-11-21T10:00:00Z'), say: (l) => lines.push(l), lines, ...over }
}

const policy = (dir: string): Record<string, unknown> => YAML.parse(readFileSync(join(dir, 'shipguard.policy.yml'), 'utf-8'))
const entries = (dir: string): Array<Record<string, unknown>> => ((policy(dir).ignore as { entries?: Array<Record<string, unknown>> }).entries ?? [])

function recordFinding(dir: string, id: string, file: string, severity: string): void {
  writeGateRecord(dir, {
    schema: 1, status: 'blocked', host: 'claude', command: 'git push', startedAt: new Date().toISOString(),
    findings: [{ id, file, line: 1, severity, blocking: true, occurrence: 'x' }],
  })
}

/** A gate run is on record, with no finding under the paths a test ignores. */
function recordRun(dir: string, notScanned: string[] = []): void {
  writeGateRecord(dir, { schema: 1, status: 'blocked', host: 'claude', command: 'git push', startedAt: new Date().toISOString(), findings: [], notScanned })
}

describe('a reason is required', () => {
  it('no reason, or a blank one: exit 2 REASON_REQUIRED, nothing written', async () => {
    const dir = project({ 'data/dump.txt': 'x' })
    for (const reason of [undefined, '', '   ']) {
      const d = deps(dir)
      const r = await runIgnore('data/dump.txt', { reason }, d)
      expect(r.exitCode).toBe(2)
      expect(d.lines.join('\n')).toContain('✗ REASON_REQUIRED: shipguard ignore needs a reason.')
      expect(d.lines.join('\n')).toContain('Fix: add --reason')
    }
    expect(existsSync(join(dir, 'shipguard.policy.yml'))).toBe(false)
  })
})

describe('path entries', () => {
  it('records { path, reason, by, date } in the policy file; by is agent without a terminal, user with one', async () => {
    const dir = project({ 'data/dump.txt': 'x', 'other.bin': 'y' })
    recordRun(dir, ['data/dump.txt', 'other.bin'])
    expect((await runIgnore('data/dump.txt', { reason: 'generated by scripts/export.sh' }, deps(dir))).exitCode).toBe(0)
    expect((await runIgnore('other.bin', { reason: 'vendor blob, checked' }, deps(dir, { isTerminal: () => true }))).exitCode).toBe(0)
    expect(entries(dir)).toEqual([
      { path: 'data/dump.txt', reason: 'generated by scripts/export.sh', by: 'agent', date: '2026-11-21' },
      { path: 'other.bin', reason: 'vendor blob, checked', by: 'user', date: '2026-11-21' },
    ])
  })

  it('keeps comments and the existing ignore.paths; creates the default policy when there is none', async () => {
    const dir = project({ 'a.dat': 'x' })
    recordRun(dir, ['a.dat'])
    writeFileSync(join(dir, 'shipguard.policy.yml'), '# my policy\nversion: 1\nignore:\n  paths:\n    - build/** # keep\n')
    await runIgnore('a.dat', { reason: 'r' }, deps(dir))
    const text = readFileSync(join(dir, 'shipguard.policy.yml'), 'utf-8')
    expect(text).toContain('# my policy')
    expect(text).toContain('# keep')
    expect((policy(dir).ignore as { paths: string[] }).paths).toEqual(['build/**'])

    const fresh = project({ 'a.dat': 'x' })
    recordRun(fresh, ['a.dat'])
    await runIgnore('a.dat', { reason: 'r' }, deps(fresh))
    expect((policy(fresh).ignore as { paths: string[] }).paths).toContain('node_modules/**')
    expect(entries(fresh)).toHaveLength(1)
  })

  it('the same target again updates the entry, never duplicates it', async () => {
    const dir = project({ 'a.dat': 'x' })
    recordRun(dir, ['a.dat'])
    await runIgnore('a.dat', { reason: 'first' }, deps(dir))
    const d = deps(dir)
    await runIgnore('a.dat', { reason: 'second' }, d)
    expect(entries(dir)).toHaveLength(1)
    expect(entries(dir)[0].reason).toBe('second')
    expect(d.lines.join('\n')).toContain('Updated the exception')
  })

  it('refuses a path outside the project, a missing path, and the project folder itself', async () => {
    const dir = project({ 'a.dat': 'x' })
    for (const target of ['../escape.txt', '/etc/passwd', '.', 'no/such/file.txt']) {
      const d = deps(dir)
      const r = await runIgnore(target, { reason: 'r' }, d)
      expect(r.exitCode, target).toBe(2)
      expect(d.lines.join('\n'), target).toContain('PATH_NOT_FOUND')
    }
    expect(existsSync(join(dir, 'shipguard.policy.yml'))).toBe(false)
  })

  it('a broken policy file is never rewritten', async () => {
    const dir = project({ 'a.dat': 'x' })
    recordRun(dir, ['a.dat'])
    writeFileSync(join(dir, 'shipguard.policy.yml'), 'ignore: [oops\n')
    const d = deps(dir)
    const r = await runIgnore('a.dat', { reason: 'r' }, d)
    expect(r.exitCode).toBe(2)
    expect(d.lines.join('\n')).toContain('INVALID_POLICY')
    expect(readFileSync(join(dir, 'shipguard.policy.yml'), 'utf-8')).toBe('ignore: [oops\n')
  })

  it('a path is taken literally: a Next.js [id] route is ignored alone, glob characters never widen it', () => {
    const rules = buildIgnoreRules({
      ignore: { paths: [], entries: [{ path: 'app/[id]/page.tsx', reason: 'r', by: 'user', date: '2026-11-21' }] },
    } as unknown as Policy)
    const user = rules.filter((r) => r.by === 'user')
    expect(user).toHaveLength(1)
    expect(user[0].reason).toBe('r')
    expect(classifyIgnored('app/[id]/page.tsx', rules)?.by).toBe('user')
    expect(classifyIgnored('app/1/page.tsx', rules)).toBeNull()
    expect(classifyIgnored('app/[id]/other.tsx', rules)).toBeNull()
  })

  it('a folder entry covers what is under it', () => {
    const rules = buildIgnoreRules({ ignore: { paths: [], entries: [{ path: 'docs', reason: 'r', by: 'user', date: 'd' }] } } as unknown as Policy)
    expect(classifyIgnored('docs/a/b.js', rules)?.by).toBe('user')
    expect(classifyIgnored('src/docs.js', rules)).toBeNull()
  })
})

describe('the critical guard covers the path form too', () => {
  it('ignoring a file or folder that holds a critical finding needs a terminal (an agent cannot dodge the finding guard by path)', async () => {
    const dir = project({ 'lib/stripe.ts': 'x', 'lib/other.ts': 'y' })
    recordFinding(dir, 'generic.secrets.stripe-live-key', 'lib/stripe.ts', 'critical')
    for (const target of ['lib/stripe.ts', 'lib']) {
      const d = deps(dir)
      const r = await runIgnore(target, { reason: 'looks fake' }, d)
      expect(r.exitCode, target).toBe(2)
      expect(d.lines.join('\n'), target).toContain('CONFIRMATION_REQUIRED')
      expect(d.lines.join('\n'), target).toContain('holds a critical finding')
    }
    expect(existsSync(join(dir, 'shipguard.policy.yml'))).toBe(false)
    // a file with no finding under it is fine, and a person at a terminal may confirm the critical one
    writeGateRecord(dir, {
      schema: 1, status: 'blocked', host: 'claude', command: 'git push', startedAt: new Date().toISOString(),
      findings: [{ id: 'generic.secrets.stripe-live-key', file: 'lib/stripe.ts', line: 1, severity: 'critical', blocking: true, occurrence: 'x' }],
      notScanned: ['lib/other.ts'],
    })
    expect((await runIgnore('lib/other.ts', { reason: 'generated' }, deps(dir))).exitCode).toBe(0)
    let asked = ''
    const yes = await runIgnore('lib/stripe.ts', { reason: 'checked with the user' }, deps(dir, { isTerminal: () => true, confirm: async (q) => { asked = q; return true } }))
    expect(yes.exitCode).toBe(0)
    expect(asked).toContain('CRITICAL')
  })

  it('with no gate record and no report at all the severity is unknown: an agent is refused', async () => {
    const dir = project({ 'a.dat': 'x' })
    const d = deps(dir)
    expect((await runIgnore('a.dat', { reason: 'r' }, d)).exitCode).toBe(2)
    expect(d.lines.join('\n')).toContain('cannot tell from the last run')
    expect((await runIgnore('a.dat', { reason: 'r' }, deps(dir, { isTerminal: () => true }))).exitCode).toBe(0)
  })

  it('the severity is read through the real report layout (latest.json points at the run report), and a hostile pointer is not followed', async () => {
    const dir = project({ 'lib/stripe.ts': 'x' })
    mkdirSync(join(dir, '.shipguard', 'reports', 'runs'), { recursive: true })
    writeFileSync(join(dir, '.shipguard', 'reports', 'runs', 'r1.json'), JSON.stringify({ findings: [{ id: 'k', file: 'lib/stripe.ts', severity: 'critical' }] }))
    writeFileSync(join(dir, '.shipguard', 'reports', 'latest.json'), JSON.stringify({ pointer: true, runJson: 'runs/r1.json' }))
    const d = deps(dir)
    expect((await runIgnore('lib/stripe.ts', { reason: 'r' }, d)).exitCode).toBe(2)
    expect(d.lines.join('\n')).toContain('holds a critical finding')
    // a pointer that leaves the reports folder is not followed: nothing usable on record, so refused (unknown)
    const hostile = project({ 'a.ts': 'x' })
    mkdirSync(join(hostile, '.shipguard', 'reports'), { recursive: true })
    writeFileSync(join(hostile, '.shipguard', 'reports', 'latest.json'), JSON.stringify({ runJson: '../../../outside.json' }))
    expect((await runIgnore('a.ts', { reason: 'r' }, deps(hostile))).exitCode).toBe(2)
  })

  it('a finding that is not critical under the path does not need a terminal', async () => {
    const dir = project({ 'lib/a.ts': 'x' })
    recordFinding(dir, 'nit', 'lib/a.ts', 'low')
    expect((await runIgnore('lib', { reason: 'r' }, deps(dir))).exitCode).toBe(0)
  })
})

describe('a path is only safe to ignore when the last run covers every file under it', () => {
  it('a file added after the scan, a file with nothing on record, and a folder holding one are all unknown: refused without a terminal', async () => {
    const dir = project({ 'lib/known.ts': 'x', 'lib/clean.ts': 'x', 'sub/a.ts': 'x' })
    recordFinding(dir, 'nit', 'lib/known.ts', 'low')
    // a secret added after the scan (newer than the record)
    writeFileSync(join(dir, 'fresh.ts'), 'sk_live_not_scanned')
    utimesSync(join(dir, 'fresh.ts'), new Date(Date.now() + 60_000), new Date(Date.now() + 60_000))
    for (const target of ['fresh.ts', 'lib/clean.ts', 'lib', 'sub']) {
      const d = deps(dir)
      const r = await runIgnore(target, { reason: 'x' }, d)
      expect(r.exitCode, target).toBe(2)
      expect(d.lines.join('\n'), target).toContain('CONFIRMATION_REQUIRED')
    }
    expect(existsSync(join(dir, 'shipguard.policy.yml'))).toBe(false)
    // the one file the record covers is fine; a person at a terminal may ignore any of them
    expect((await runIgnore('lib/known.ts', { reason: 'x' }, deps(dir))).exitCode).toBe(0)
    expect((await runIgnore('fresh.ts', { reason: 'x' }, deps(dir, { isTerminal: () => true }))).exitCode).toBe(0)
  })

  it('a known file that was edited after the record is unknown again', async () => {
    const dir = project({ 'lib/known.ts': 'x' })
    recordFinding(dir, 'nit', 'lib/known.ts', 'low')
    utimesSync(join(dir, 'lib/known.ts'), new Date(Date.now() + 60_000), new Date(Date.now() + 60_000))
    expect((await runIgnore('lib/known.ts', { reason: 'x' }, deps(dir))).exitCode).toBe(2)
  })

  it('an unscanned file the run named (too large, unknown binary) can be ignored by an agent: that is the coverage flow', async () => {
    const dir = project({ 'big.txt': 'x' })
    recordRun(dir, ['big.txt'])
    expect((await runIgnore('big.txt', { reason: 'generated by scripts/export.sh, checked' }, deps(dir))).exitCode).toBe(0)
  })
})

describe('finding entries and the critical rule', () => {
  it('a non-critical finding on record is ignored from a non-terminal; the entry names rule and file', async () => {
    const dir = project()
    recordFinding(dir, 'missing_idempotency', 'app/api/webhooks/stripe/route.ts', 'low')
    const r = await runIgnore('missing_idempotency', { file: 'app/api/webhooks/stripe/route.ts', reason: 'repeats are handled by a unique index on event.id' }, deps(dir))
    expect(r.exitCode).toBe(0)
    expect(entries(dir)).toEqual([
      { finding: 'missing_idempotency', file: 'app/api/webhooks/stripe/route.ts', reason: 'repeats are handled by a unique index on event.id', by: 'agent', date: '2026-11-21' },
    ])
  })

  it('a critical finding needs a terminal: refused for an agent, nothing written', async () => {
    const dir = project()
    recordFinding(dir, 'generic.secrets.stripe-live-key', 'lib/stripe.ts', 'critical')
    const d = deps(dir)
    const r = await runIgnore('generic.secrets.stripe-live-key', { file: 'lib/stripe.ts', reason: 'looks fake' }, d)
    expect(r.exitCode).toBe(2)
    expect(d.lines.join('\n')).toContain('CONFIRMATION_REQUIRED')
    expect(d.lines.join('\n')).toContain('can only be ignored from a terminal, by a person')
    expect(existsSync(join(dir, 'shipguard.policy.yml'))).toBe(false)
  })

  it('a finding whose severity is not on record is treated the same way (deny by default)', async () => {
    const dir = project()
    const d = deps(dir)
    const r = await runIgnore('some_rule', { file: 'a.ts', reason: 'r' }, d)
    expect(r.exitCode).toBe(2)
    expect(d.lines.join('\n')).toContain('cannot tell from the last run how severe some_rule is')
    expect(existsSync(join(dir, 'shipguard.policy.yml'))).toBe(false)
  })

  it('at a terminal a critical finding asks once: no = nothing changed, yes = written with by: user', async () => {
    const dir = project()
    recordFinding(dir, 'generic.secrets.stripe-live-key', 'lib/stripe.ts', 'critical')
    const no = await runIgnore('generic.secrets.stripe-live-key', { file: 'lib/stripe.ts', reason: 'r' }, deps(dir, { isTerminal: () => true, confirm: async () => false }))
    expect(no.exitCode).toBe(2)
    expect(existsSync(join(dir, 'shipguard.policy.yml'))).toBe(false)
    let asked = ''
    const yes = await runIgnore('generic.secrets.stripe-live-key', { file: 'lib/stripe.ts', reason: 'r' }, deps(dir, { isTerminal: () => true, confirm: async (q) => { asked = q; return true } }))
    expect(yes.exitCode).toBe(0)
    expect(asked).toContain('CRITICAL')
    expect(entries(dir)[0].by).toBe('user')
  })

  it('the severity can also come from the last report', async () => {
    const dir = project()
    mkdirSync(join(dir, '.shipguard', 'reports'), { recursive: true })
    writeFileSync(join(dir, '.shipguard', 'reports', 'latest.json'), JSON.stringify({ findings: [{ id: 'nit', file: 'a.ts', severity: 'low' }] }))
    expect((await runIgnore('nit', { file: 'a.ts', reason: 'r' }, deps(dir))).exitCode).toBe(0)
  })

  it('--file needs a finding id, and a target that is neither a path nor an id is refused', async () => {
    const dir = project()
    for (const [target, file] of [['not a finding id', 'a.ts'], ['!!', undefined]] as const) {
      const d = deps(dir)
      expect((await runIgnore(target, { file, reason: 'r' }, d)).exitCode).toBe(2)
    }
  })
})

describe('how the policy entries are read', () => {
  it('an entry without a reason is NOT honoured and says so; an entry with both path and finding is skipped', () => {
    const warn = vi.spyOn(console, 'error').mockImplementation(() => undefined)
    const read = readIgnoreEntries({
      ignore: {
        paths: [],
        entries: [
          { path: 'a.dat' },
          { finding: 'x', reason: '   ' },
          { path: 'b', finding: 'y', reason: 'r' },
          { path: 'ok.dat', reason: 'r', by: 'user', date: '2026-11-21' },
        ],
      },
    } as unknown as Policy)
    expect(read.map((e) => e.path)).toEqual(['ok.dat'])
    expect(warn.mock.calls.map((c) => String(c[1] ?? c[0])).join('\n')).toMatch(/has no reason, so it is not applied/)
    warn.mockRestore()
  })

  it('finding entries suppress like an inline comment: kept in the report, marked suppressed, never blocking', () => {
    const f = (id: string, file: string): Finding => ({ id, file, severity: 'high', blocking: true, title: 't' } as unknown as Finding)
    const list = [f('r1', 'a.ts'), f('r1', 'b.ts'), f('r2', 'a.ts')]
    applyPolicyIgnores(list, [
      { finding: 'r1', file: 'a.ts', reason: 'r', by: 'user', date: 'd' },
      { finding: 'r2', reason: 'everywhere', by: 'user', date: 'd' },
    ])
    expect(list.map((x) => [x.suppressed ?? false, x.blocking])).toEqual([[true, false], [false, true], [true, false]])
    expect(list).toHaveLength(3)
  })
})

describe('the scanner honours the entries (built CLI)', () => {
  const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../../')
  const distCli = resolve(pkgRoot, 'dist/cli.js')
  beforeAll(() => {
    if (!existsSync(distCli)) execFileSync('npx', ['tsup'], { cwd: pkgRoot, stdio: 'inherit' })
  }, 240_000)

  const scan = (dir: string) => spawnSync(process.execPath, [distCli, 'scan', '--all', '--json', '--strict'], { cwd: dir, encoding: 'utf-8' })
  const KEY = `sk_live_${'abcdefghijklmnopqrstuvwx1234567'}`

  it('a path entry removes the file from the scan and is counted as ignored by the user', async () => {
    const dir = project({ 'lib/stripe.ts': `export const k = "${KEY}"\n` })
    execFileSync('git', ['init', '-q'], { cwd: dir })
    expect(scan(dir).status).toBe(1)
    // the scan left a report with a critical finding in it: only a person at a terminal may ignore the file
    expect((await runIgnore('lib/stripe.ts', { reason: 'test fixture, checked' }, deps(dir))).exitCode).toBe(2)
    expect((await runIgnore('lib/stripe.ts', { reason: 'test fixture, checked' }, deps(dir, { isTerminal: () => true }))).exitCode).toBe(0)
    const after = scan(dir)
    expect(after.status).toBe(0)
    expect(JSON.parse(after.stdout).coverage.ignoredByUser).toBe(1)
  })

  it('a finding entry for one file suppresses it there only', async () => {
    const dir = project({ 'lib/a.ts': `export const k = "${KEY}"\n`, 'lib/b.ts': `export const k = "${KEY}"\n` })
    execFileSync('git', ['init', '-q'], { cwd: dir })
    recordFinding(dir, 'generic.secrets.stripe-live-key', 'lib/a.ts', 'high')
    expect((await runIgnore('generic.secrets.stripe-live-key', { file: 'lib/a.ts', reason: 'placeholder' }, deps(dir))).exitCode).toBe(0)
    const out = scan(dir)
    expect(out.status).toBe(1)
    const json = JSON.parse(out.stdout) as { findings: Array<{ file: string; suppressed?: boolean; blocking: boolean }> }
    const byFile = Object.fromEntries(json.findings.map((x) => [x.file, x]))
    expect(byFile['lib/a.ts'].suppressed).toBe(true)
    expect(byFile['lib/a.ts'].blocking).toBe(false)
    expect(byFile['lib/b.ts'].blocking).toBe(true)
  })

  it('an entry with no reason in the file changes nothing: the scan still blocks', () => {
    const dir = project({ 'lib/a.ts': `export const k = "${KEY}"\n`, 'shipguard.policy.yml': 'version: 1\nignore:\n  paths: []\n  entries:\n    - path: lib/a.ts\n' })
    execFileSync('git', ['init', '-q'], { cwd: dir })
    expect(scan(dir).status).toBe(1)
  })
})
