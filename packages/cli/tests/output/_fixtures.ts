export function result(findings: Finding[], o: Partial<ScanResult> = {}): ScanResult {
  const count = (sev: string) => findings.filter((f) => f.severity === sev).length
  const blocking = findings.filter((f) => f.blocking).length
  const rec = blocking > 0 ? 'DO_NOT_SHIP' : findings.length > 0 ? 'REVIEW_BEFORE_SHIP' : 'SAFE_TO_SHIP'
  return {
    findings,
    riskScore: {
      score: blocking > 0 ? 100 : findings.length > 0 ? 30 : 0,
      recommendation: rec,
      totalFindings: findings.length,
      criticalCount: count('critical'),
      highCount: count('high'),
      mediumCount: count('medium'),
      lowCount: count('low'),
      infoCount: count('info'),
      blockingCount: blocking,
    },
    recommendation: rec,
    filesScanned: 16,
    timestamp: '2026-11-17T23:07:00.000Z',
    policyUsed: 'my-app',
    runId: '247f9045-8511-4647-80fd-a4945e28d135',
    ...o,
  }
}

