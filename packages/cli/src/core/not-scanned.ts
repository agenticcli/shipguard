/**
 * not-scanned.ts: the "Not scanned" block of the screen and report (spec 01 A3d, spec 06 "Skipped files").
 *
 * Every file the scan could not read is NAMED, with a plain reason and one fix line. Reason lines are
 * never cut mid-word. One source string per code (the fix text is the same on screen and in the report).
 */

import { statSync } from 'node:fs'
import { join } from 'node:path'
import type { ScanResult, DegradeCode } from '@agenticcli/shared'

export interface NotScannedEntry {
  /** Project-relative file name; null when only a count is known. */
  path: string | null
  code: DegradeCode
  /** Plain words, e.g. `too large (700 KB, limit 512 KB)`. */
  reason: string
  /** Fix lines (first line is the instruction; later lines continue it). */
  fix: string[]
  /** Number of files when `path` is null. */
  count?: number
}

export interface NotScannedSummary {
  entries: NotScannedEntry[]
  /** Degraded reasons that are not about files (rulebook unavailable, compile failure, ...). */
  otherReasons: Array<{ code: DegradeCode; text: string }>
  /** Files that could not be scanned (sum of the degrading skip counters). */
  fileCount: number
}

/** Quote a path for a copy-pasteable shell command (spec 01 rule 7: spaces and special characters). */
export function shellQuote(s: string): string {
  if (/^[A-Za-z0-9_@%+=:,./-]+$/.test(s)) return s
  return `'${s.replace(/'/g, `'\\''`)}'`
}

function formatSize(bytes: number): string {
  if (bytes >= 1024 * 1024) return `${(bytes / (1024 * 1024)).toFixed(1).replace(/\.0$/, '')} MB`
  return `${Math.max(1, Math.round(bytes / 1024))} KB`
}

const ASK_FIRST =
  '(ask the user first, or give a reason you checked, for example: listed in .gitignore, generated by <script>)'

function ignoreCmd(path: string): string {
  return `shipguard ignore ${shellQuote(path)} --reason "<why: what this file is>"`
}

export interface NotScannedOptions {
  /** Scan root, used only to read a file's size for the "too large" reason. */
  cwd?: string
  /** The size cap in force (policy `limits.maxFileSizeBytes`). */
  maxFileSizeBytes?: number
}

export function collectNotScanned(result: ScanResult, opts: NotScannedOptions = {}): NotScannedSummary {
  const cov = result.coverage
  const entries: NotScannedEntry[] = []
  let fileCount = 0

  if (cov) {
    for (const p of cov.files.tooLarge) {
      let size: string | null = null
      if (opts.cwd) {
        try {
          size = formatSize(statSync(join(opts.cwd, p)).size)
        } catch {
          size = null // file vanished or is unreadable: say less, never guess a size
        }
      }
      const limit = opts.maxFileSizeBytes ? `limit ${formatSize(opts.maxFileSizeBytes)}` : null
      const inner = [size, limit].filter((x): x is string => x !== null).join(', ')
      entries.push({
        path: p,
        code: 'FILE_TOO_LARGE',
        reason: inner ? `too large (${inner})` : 'too large',
        fix: [
          `it is a text file, so raise limits.maxFileSizeBytes in shipguard.policy.yml first. Or exclude it: ${ignoreCmd(p)}`,
          ASK_FIRST,
        ],
      })
    }
    for (const p of cov.files.unknownBinary) {
      entries.push({
        path: p,
        code: 'UNSCANNED_UNKNOWN_BINARY',
        reason: 'binary data with unknown format (NUL bytes)',
        fix: [`find out what it is. If the user confirms it is safe: ${ignoreCmd(p)}`],
      })
    }
    for (const p of cov.files.symlink) {
      entries.push({
        path: p,
        code: 'SYMLINK_SKIPPED',
        reason: 'symlink, not followed',
        fix: ['replace the symlink with the real file or folder to have it scanned (ShipGuard never follows symlinks)'],
      })
    }
    const utf8Names = cov.files.invalidUtf8 ?? []
    for (const p of utf8Names) {
      entries.push({
        path: p,
        code: 'INVALID_UTF8',
        reason: 'not valid text (skipped on purpose so a secret split by bad bytes is not mangled)',
        fix: [`find out what it is; only if the user confirms it is safe: ${ignoreCmd(p)}`],
      })
    }
    // Names are capped at 50 in coverage; the exact count stays, so a larger remainder is one count line.
    if (cov.skipped.invalidUtf8 > utf8Names.length) {
      const rest = cov.skipped.invalidUtf8 - utf8Names.length
      entries.push({
        path: null,
        count: rest,
        code: 'INVALID_UTF8',
        reason: `${rest} more file(s) not valid text`,
        fix: ['find out what they are; only if the user confirms they are safe: shipguard ignore <file> --reason "<why: what this file is>"'],
      })
    }
    const unreadableNames = cov.files.unreadable ?? []
    for (const p of unreadableNames) {
      entries.push({
        path: p,
        code: 'UNREADABLE_FILE',
        reason: 'cannot be read (permission or removed during the scan)',
        fix: ['fix permissions, then re-run'],
      })
    }
    if (cov.skipped.unreadable > unreadableNames.length) {
      const rest = cov.skipped.unreadable - unreadableNames.length
      entries.push({
        path: null,
        count: rest,
        code: 'UNREADABLE_FILE',
        reason: `${rest} more file(s) cannot be read (permission or removed during the scan)`,
        fix: ['fix permissions, then re-run'],
      })
    }
    if (cov.truncated) {
      entries.push({
        path: null,
        count: cov.truncated.notReached,
        code: 'OUTPUT_TRUNCATED',
        reason: `limit reached (${cov.truncated.by === 'maxFiles' ? 'file count' : 'total size'}); ${cov.truncated.notReached} file(s) not scanned`,
        fix: ['raise limits.maxFiles or scan a subfolder'],
      })
    }
    fileCount =
      cov.skipped.tooLarge +
      cov.skipped.unknownBinary +
      cov.skipped.symlink +
      cov.skipped.invalidUtf8 +
      cov.skipped.unreadable
  }

  const fileCodes = new Set<DegradeCode>([
    'FILE_TOO_LARGE',
    'UNSCANNED_UNKNOWN_BINARY',
    'SYMLINK_SKIPPED',
    'INVALID_UTF8',
    'UNREADABLE_FILE',
    'OUTPUT_TRUNCATED',
    'NO_FILES_SCANNED',
  ])
  const otherReasons: NotScannedSummary['otherReasons'] = []
  for (const r of result.degradedReasons ?? []) {
    if (fileCodes.has(r.code)) continue
    otherReasons.push({ code: r.code, text: r.detail ? r.detail : OTHER_REASON_TEXT[r.code] ?? 'part of this scan did not run' })
  }
  return { entries, otherReasons, fileCount }
}

const OTHER_REASON_TEXT: Partial<Record<DegradeCode, string>> = {
  PRO_RULES_UNAVAILABLE: 'the full rulebook was not available for this scan',
  CODEREF_SKIPPED: 'some rule checks were skipped',
  COMPILE_FAILURE: 'some rules could not be compiled',
}
